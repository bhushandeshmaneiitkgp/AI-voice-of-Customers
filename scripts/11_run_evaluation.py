def _jsonable(value: Any) -> Any:
    """Coerce numpy scalars, which json refuses and which pandas returns everywhere."""
    if hasattr(value, "item"):
        return value.item()
    if isinstance(value, (set, frozenset)):
        return sorted(value)
    raise TypeError(f"{type(value).__name__} is not JSON serialisable")


def _rate_cell(payload: dict[str, Any] | None) -> str:
    """A rate with its interval, or an honest dash."""
    if not payload or payload.get("value") is None:
        return "—"
    low, high = payload.get("ci_low"), payload.get("ci_high")
    text = f"{payload['value'] * 100:.1f}%"
    if low is not None and high is not None:
        text += f" ({low * 100:.1f}–{high * 100:.1f})"
    return text


