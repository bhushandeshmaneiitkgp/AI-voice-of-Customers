"""
Run every evaluation the project can currently support, and say plainly what it cannot.

This is the second half of Phase 9. It makes no API calls and costs nothing.

    # everything
    python scripts/11_run_evaluation.py

    # skip the retrieval study (loads a sentence-transformer, ~30s)
    python scripts/11_run_evaluation.py --skip-retrieval

    # tighter intervals on the fault study
    python scripts/11_run_evaluation.py --faults 500

Four studies, in descending order of what they license:

1. **Accuracy against the gold set** -- only runs if a human has labelled it.
   When ``data/eval/gold_labels.csv`` is absent, this section reports its own
   absence rather than being silently skipped, because a missing accuracy
   number is the single most important fact about the current evaluation.
2. **Validator capture rates** -- injects known faults into real enrichments and
   measures what the pipeline's own validators catch, with a false-positive
   control on untouched input. Followed by an audit of what those validators
   let through into the shipped dataset, which is not the same question.
3. **Retrieval precision** -- unfiltered search scored against the corpus labels
   and, more importantly, against the base rate.
4. **Inter-model agreement** -- computed from the per-model caches, and labelled
   as agreement everywhere it appears.

Reads  : data/processed/reviews_enriched.parquet
         data/processed/review_labels.parquet
         artifacts/enrichment_cache_<model>.json
         data/eval/gold_labels.csv                (optional)
Writes : data/processed/evaluation_results.json
         reports/EVALUATION.md
"""

