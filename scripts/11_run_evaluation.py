def run_fault_study(reviews: pd.DataFrame, model_key: str, per_kind: int, seed: int, taxonomy):
    payloads = agreement_mod.load_cache(Paths.enrichment_cache(model_key))
    if not payloads:
        return pd.DataFrame(), {}, {"rate": None, "kinds": {}, "pool": 0, "population": 0}

    texts = dict(zip(reviews["review_id"], reviews["review_text"]))
    payloads = {rid: p for rid, p in payloads.items() if rid in texts}

    # One validation pass over the whole cache serves both halves of the study:
    # the subjects to inject into, and the false-positive control that says what
    # the validators do to input nobody touched.
    control = faults_mod.clean_baseline(payloads, texts, taxonomy)

    study = faults_mod.run_fault_study(
        payloads, texts, taxonomy, per_kind=per_kind, seed=seed, pool=control.clean_ids
    )
    baseline = {
        "rate": control.rate.as_dict(),
        "kinds": control.kinds,
        "pool": len(control.clean_ids),
        "population": control.examined,
    }
    return study, faults_mod.summarise(study), baseline


def run_agreement(model_keys: list[str]) -> list[dict[str, Any]]:
    caches = {}
    for key in model_keys:
        payloads = agreement_mod.load_cache(Paths.enrichment_cache(key))
        if payloads:
            caches[key] = payloads
    if len(caches) < 2:
        return []

    names = sorted(caches)
    results = []
    for i, left in enumerate(names):
        for right in names[i + 1:]:
            results.append(
                agreement_mod.compare_models(caches[left], caches[right], left, right).as_dict()
            )
    return results


