"""
Run exploratory data analysis over the cleaned corpus.

Run:
    python scripts/03_run_eda.py

Reads  : data/interim/reviews_clean.parquet   (read-only)
         data/interim/cleaning_report.json    (for reconciliation)
         config/taxonomy.yaml
Writes : reports/EDA_REPORT.md
         reports/figures/*.png

No LLM is used. Everything here is deterministic and reproducible.
The cleaned dataset is never modified.
"""

